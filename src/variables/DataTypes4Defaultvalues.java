package variables;

public class DataTypes4Defaultvalues {
	// Pr
	// number types default value is zero
	byte b;
	short s;
	int i;
	long l;
	
   //Decimal data types default value is 0.0
	float f;
	double d;
	
	// grade type default value is empty space
	char c;
	
	// Boolian type default value is false
	boolean bool;
	
	// String Data Type default value is null
	String st;
	
	public static void main(String[] args) {
		DataTypes4Defaultvalues dt4=new DataTypes4Defaultvalues();
		
		System.out.println(dt4.b);
		System.out.println(dt4.s);
		System.out.println(dt4.i);
		System.out.println(dt4.l);
		System.out.println(dt4.f);
		System.out.println(dt4.d);
		System.out.println(dt4.c);
		System.out.println(dt4.bool);
		System.out.println(dt4.st);
		
		
	}
	

}
