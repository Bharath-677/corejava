package variables;

public class DataTypes1 {
	
	public static void main(String[] args) {
		
		//primitive dataTypes
		
		//number data types-4
		byte id=127;       //1 byte
		short num=12123;   // 2 byte
		int value=701378115;  //4 byte
		long mobile=701378115232323232L; //8byte
		
		//decimal data types-2
		
		double amt=12.78;  //8 byte
		float miles=1.23f; //4 byte
		
		
		//char type-1
		
		char grade='2';
		
		//boolean type-1
		
		boolean areyouindian=true;
		
		
		
		System.out.println("Id value:"+id);
		System.out.println("num:"+num);
		System.out.println("value:"+value);
		System.out.println("mobile num:"+mobile);
		System.out.println("amount:"+amt);
		System.out.println("miles:"+ miles);
		System.out.println("grade:"+grade);
		System.out.println("Are you Indian:"+areyouindian);
		
		
		
	}
	
	

}
